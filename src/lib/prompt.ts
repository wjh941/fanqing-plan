function worksBlock(form: AccountForm): string {
  const lines = form.works
    .filter((w) => w.title.trim())
    .map((w, i) => {
      const parts = [
        `发布时间:${w.date.trim() || '未填写'}`,
        `标题:${w.title.trim()}`,
        `内容简述:${w.summary.trim() || '未填写'}`,
        `数据:点赞 ${w.likes.trim() || '未填写'} / 收藏 ${w.collects.trim() || '未填写'} / 播放 ${w.plays.trim() || '未填写'}`,
      ]
      return `${i + 1}. ${parts.join(' | ')}`
    })
  return lines.join('\n')
}

export function buildUserContent(form: AccountForm): string {
  const extras: string[] = []
  if (form.positioningConfused) {
    extras.push(
      `- 博主目前对自己的定位很迷茫:不知道自己的人设是什么,也不清楚哪条内容算自己的"爆点"。赛道&人设一栏可能为空或很模糊。
  请在模块1中增加小节「#### 你的定位,从数据里反推」:基于他的历史作品给出 2~3 个可选定位方向,每个方向附:数据依据(引用他自己的作品与数据)、适合吸引的人群、优势与风险;最后明确推荐"先按哪个方向跑 4 周实验",模块2 的选题也要围绕这个推荐方向展开。
  语气上请多安抚:定位迷茫是断更后的常见状态,不是能力问题——"你不知道自己是谁,但你的数据知道"。`,
    )
  }
  if (form.wantsMonetize) {
    extras.push(
      `- 博主很关心后续怎么有收益。请在模块5之后追加输出「### 模块6:变现路径规划」:
  按重启节奏分三阶段(重启期 / 标签稳定后 / 数据成熟后),每阶段给出与该账号赛道匹配的合规变现方式、开启的大致门槛(注明"以平台最新规则为准")、以及现在就能做的低成本"变现预研"动作(如记录评论区求链接的需求信号)。
  必须明确提醒:重启期不建议急着接商业推广,大概率会打乱正在回暖的账号标签;不推荐三无产品与夸大宣传;收益因人而异,所有表述不构成收益承诺。`,
    )
  }

  const nicheLine = form.niche.trim()
    ? form.niche.trim()
    : form.positioningConfused
      ? '(未填写——博主自述定位迷茫,请务必从历史作品数据反推)'
      : '未填写'

  return `【我的账号信息】
1. 账号赛道&人设:${nicheLine}
2. 断更时长:${form.gapDuration.trim()}
3. 断更原因:${form.gapReason.trim() || '未填写'}
4. 重启目标:${form.goal.trim()}
5. 历史作品(${form.works.filter((w) => w.title.trim()).length} 条,含数据):
${worksBlock(form)}${extras.length > 0 ? `\n【本次特别说明】\n${extras.join('\n')}` : ''}

请基于以上信息,严格按照系统规则${form.wantsMonetize ? '依次输出全部 6 个模块(含模块6)' : '依次输出全部 5 个模块'}。`
}

export function buildMessages(form: AccountForm): ChatMessage[] {
  return [
    { role: 'system', content: SYSTEM_PROMPT },
    { role: 'user', content: buildUserContent(form) },
  ]
}

/** 追问微调:只重写某一个模块 */
export function buildRefineMessages(
  form: AccountForm,
  report: string,
  moduleN: number,
  instruction: string,
): ChatMessage[] {
  const meta = MODULES.find((m) => m.n === moduleN)
  const title = meta ? meta.title : `模块${moduleN}`
  return [
    { role: 'system', content: SYSTEM_PROMPT },
    { role: 'user', content: buildUserContent(form) },
    { role: 'assistant', content: report },
    {
      role: 'user',
      content: `请只重写上面的「${title}」(模块${moduleN})这一部分,保持整体风格、人设判断和其他模块不变。

我的具体要求:${instruction}

输出要求:直接从 "### 模块${moduleN}:${title}" 标题开始,输出该模块的完整内容,不要输出其他模块,不要任何解释;输出末尾单独一行附上:本方案仅为内容创作策略参考,无法干预平台算法,不保证流量效果。`,
    },
  ]
}
